#!/usr/bin/env node
/*
 * 2 Hub 試験台（2026-10-12、所有者承認済み。AGENTS.md「Local Hub development environment」）。
 *
 *   node scripts/dev-hub-b.mjs up        Federation A/B と Hub B を起動し、migration と試験用利用者を入れる
 *   node scripts/dev-hub-b.mjs down      すべて止める（試験の最後に必ず実行する）
 *   node scripts/dev-hub-b.mjs status    ポートと pid を表示する
 *   node scripts/dev-hub-b.mjs migrate   Hub B と両 Federation の migration だけを流す
 *   node scripts/dev-hub-b.mjs seed      試験用利用者を（再）投入する（起動中の Federation が要る）
 *   node scripts/dev-hub-b.mjs reset     down のあと .wrangler/state-hub-b を消す（その配下だけ）
 *
 * 構成
 *   Federation A  http://127.0.0.1:8787   状態 .wrangler/state-hub-b/federation-a/   （Hub A の代役。試験用の新しい状態）
 *   Federation B  http://127.0.0.1:8797   状態 .wrangler/state-hub-b/federation-b/
 *   Hub B         http://127.0.0.1:3030   状態 .wrangler/state-hub-b/hub/  ← next.config.mjs が /users 等を Federation B へ回す
 *
 * 守ること
 *   - 3020 の Hub A と .wrangler/state には触れない。読まない、写さない、migration も流さない。
 *   - 秘密は毎回ここで新しく作る試験値だけ。Hub A の .dev.vars は読まない。
 *     置き場は .wrangler/state-hub-b/run/（.gitignore の .wrangler/ に入る）。
 *   - すべて --local。リモートの資源には接続しない。
 */
import { spawn, spawnSync } from "node:child_process";
import { generateKeyPairSync, randomBytes } from "node:crypto";
import {
  closeSync, existsSync, mkdirSync, openSync, readFileSync, rmSync, writeFileSync,
} from "node:fs";
import net from "node:net";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { buildValues, renderConfigs } from "./materialize-selfhost-config.mjs";

const hubRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = path.resolve(hubRoot, "../..");
const wranglerBin = path.join(repoRoot, "node_modules/wrangler/bin/wrangler.js");
const nextBin = path.join(repoRoot, "node_modules/next/dist/bin/next");

export const STATE_B = path.join(hubRoot, ".wrangler", "state-hub-b");
const RUN = path.join(STATE_B, "run");
const PERSIST = {
  hub: path.join(STATE_B, "hub"),
  fedA: path.join(STATE_B, "federation-a"),
  fedB: path.join(STATE_B, "federation-b"),
};

const HUB_B_PORT = 3030;
const FED_B_PORT = 8797;
const FED_A_PORT = 8787;
const ORIGIN_A = process.env.HUB_A_FEDERATION_ORIGIN?.trim() || `http://127.0.0.1:${FED_A_PORT}`;
const ORIGIN_B = `http://127.0.0.1:${HUB_B_PORT}`;
// 段階2の試験が立てる、第三の Hub の代役（scripts/federation-two-hub-e2e.mjs が 8899 で待ち受ける）。
// 3つめの家へ移る試験のために、両方の Federation がこの origin を loopback の相手として許す。
export const STUB_C_ORIGIN = "http://127.0.0.1:8899";
const DEAD_ORIGIN = "http://127.0.0.1:8999"; // Hub B が他サービスの本物の Worker に当たらないよう、行き止まりへ向ける

const USERS = {
  a: [{ id: "testbed-alice", handle: "alice", displayName: "Alice (testbed A)" }],
  b: [
    { id: "testbed-bob", handle: "bob", displayName: "Bob (testbed B)" },
    { id: "testbed-carol", handle: "carol", displayName: "Carol (testbed B)" },
  ],
};

function assertInsideStateB(target) {
  const parts = path.resolve(target).split(path.sep);
  const at = parts.lastIndexOf("state-hub-b");
  if (at < 1 || parts[at - 1] !== ".wrangler" || path.resolve(target).startsWith(path.join(hubRoot, ".wrangler", "state") + path.sep)) {
    throw new Error(`refusing to touch a path outside .wrangler/state-hub-b: ${target}`);
  }
}

function portFree(port) {
  return new Promise((resolve) => {
    const server = net.createServer();
    server.once("error", () => resolve(false));
    server.once("listening", () => server.close(() => resolve(true)));
    server.listen(port, "127.0.0.1");
  });
}

function loadSecrets() {
  const file = path.join(RUN, "secrets.json");
  assertInsideStateB(file);
  if (existsSync(file)) return JSON.parse(readFileSync(file, "utf8"));
  const pair = () => {
    const { privateKey, publicKey } = generateKeyPairSync("rsa", { modulusLength: 2048 });
    return {
      privatePem: privateKey.export({ type: "pkcs8", format: "pem" }).toString(),
      publicPem: publicKey.export({ type: "spki", format: "pem" }).toString(),
    };
  };
  const secrets = {
    note: "test-only values generated by scripts/dev-hub-b.mjs; never reuse elsewhere",
    fedA: { serviceSecret: randomBytes(32).toString("hex"), ...pair() },
    fedB: { serviceSecret: randomBytes(32).toString("hex"), ...pair() },
  };
  mkdirSync(RUN, { recursive: true });
  writeFileSync(file, JSON.stringify(secrets, null, 2));
  return secrets;
}

const dotenvValue = (value) => `"${value.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\r?\n/g, "\\n")}"`;

/*
 * Self-host kit materialization (docs/hub-decentralization/DESIGN.md 8.3, acceptance test 2).
 * Hub B and Federation B configs come from the kit templates via materialize-selfhost-config.mjs
 * with the `local` profile (no routes, assets, alias, crons, observability; environment=development)
 * and absolute paths (they live under .wrangler/state-hub-b/run/, not in the app directory).
 * Placeholder values only; never written to the app's wrangler.selfhost*.jsonc. A small, explicit dev
 * overlay then adds what the kit intentionally does not carry.
 */
const PLACEHOLDER = {
  name: "Testbed Hub",
  contact: "testbed@example.invalid",
  zone: "testbed.invalid", // routes never apply to a local --local run; the zone just has to be non-jkamma
};
const uuid = (tail) => `00000000-0000-4000-8000-${tail}`;

/** The kit must stay free of jkamma-only hosts and bindings. Throws with the offending item. */
export function assertKitConfigIsNeutral(label, text, { overlay = false } = {}) {
  if (/jkamma\.com/i.test(text)) throw new Error(`${label}: materialized config mentions jkamma.com`);
  const config = JSON.parse(text);
  if (config.services) throw new Error(`${label}: materialized config declares service bindings`);
  const jkammaOnly = /^(HUB_)?(VAULT|MUSIC|AI|IDENTITY|COMMERCE|COMPUTE|MAIL|SOCIAL_PUBLISHER|ACCOUNT|ADS_QUARANTINE|ADS_ASSETS)(_|$)/;
  const names = [
    ...Object.keys(config.vars ?? {}),
    ...(config.r2_buckets ?? []).map((e) => e.binding),
    ...(config.d1_databases ?? []).map((e) => e.binding),
    ...(config.queues?.producers ?? []).map((e) => e.binding),
    ...(config.durable_objects?.bindings ?? []).map((e) => e.name),
  ];
  const bad = names.find((n) => jkammaOnly.test(n));
  if (bad) throw new Error(`${label}: materialized config contains jkamma-only binding or var ${bad}`);
  if (!overlay && Object.hasOwn(config.vars ?? {}, "HUB_JKAMMA_SERVICES")) {
    throw new Error(`${label}: kit config must not carry HUB_JKAMMA_SERVICES (it is a dev overlay only)`);
  }
}

function materializeKit(origin, { hubTail, fedTail, namePrefix }) {
  const values = buildValues({
    origin, ...PLACEHOLDER, profile: "local", namePrefix, d1HubId: uuid(hubTail), d1FederationId: uuid(fedTail),
  });
  const rendered = renderConfigs(values, { profile: "local", absolutePaths: true });
  assertKitConfigIsNeutral("hub", rendered.hub);
  assertKitConfigIsNeutral("federation", rendered.federation);
  return { hub: JSON.parse(rendered.hub), federation: JSON.parse(rendered.federation) };
}

function writeFederationConfig(name, { port, origin, peers, secrets }) {
  const dir = path.join(RUN, name);
  assertInsideStateB(dir);
  mkdirSync(dir, { recursive: true });
  const suffix = name === "federation-a" ? "a" : "b";
  const { federation: config } = materializeKit(origin, {
    hubTail: "000000000000", fedTail: `0000000000f${suffix}`, namePrefix: `testbed-${suffix}`,
  });
  // --- dev overlay (not in the kit): loopback peers and fast local retries. ---
  config.vars.FEDERATION_DEV_LOOPBACK_PEERS = peers.join(",");
  Object.assign(config.queues.consumers[0], { max_batch_timeout: 1, max_retries: 3 });
  assertKitConfigIsNeutral(`federation-${suffix} (after overlay)`, JSON.stringify(config), { overlay: true });
  writeFileSync(path.join(dir, "wrangler.jsonc"), JSON.stringify(config, null, 2));
  writeFileSync(path.join(dir, ".dev.vars"), [
    `HUB_FEDERATION_SECRET=${secrets.serviceSecret}`,
    `FEDERATION_PRIVATE_KEY_PEM=${dotenvValue(secrets.privatePem)}`,
    `FEDERATION_PUBLIC_KEY_PEM=${dotenvValue(secrets.publicPem)}`,
    "",
  ].join("\n"));
  return { dir, config: path.join(dir, "wrangler.jsonc"), port };
}

function writeHubConfig() {
  const dir = path.join(RUN, "hub");
  assertInsideStateB(dir);
  mkdirSync(dir, { recursive: true });
  const { hub: config } = materializeKit(ORIGIN_B, { hubTail: "00000000b003", fedTail: "0000000000fb", namePrefix: "testbed-b" });
  // --- dev overlay (not in the kit) ---
  // Hub B is a plain self-hosted Hub: no jkamma-only services. The kit has no such switch (it is a jkamma
  // runtime flag), so this is an explicit overlay.
  config.vars.HUB_JKAMMA_SERVICES = "0";
  assertKitConfigIsNeutral("hub (after overlay)", JSON.stringify(config), { overlay: true });
  writeFileSync(path.join(dir, "wrangler.jsonc"), JSON.stringify(config, null, 2));
  // wrangler は設定ファイルと同じ場所の .dev.vars を読む。ここに置いた空に近い物が、apps/hub/.dev.vars（Hub A の秘密）の代わりになる。
  writeFileSync(path.join(dir, ".dev.vars"), "HUB_DEPLOYMENT_ENVIRONMENT=development\n");
  return { dir, config: path.join(dir, "wrangler.jsonc") };
}

function wranglerEnv() {
  return { ...process.env, WRANGLER_SEND_METRICS: "false", NO_COLOR: "1" };
}

function runWrangler(args, options = {}) {
  const result = spawnSync(process.execPath, [wranglerBin, ...args], {
    cwd: options.cwd ?? repoRoot, env: wranglerEnv(), encoding: "utf8", maxBuffer: 256 * 1024 * 1024, timeout: options.timeout ?? 600_000,
  });
  if (result.status !== 0) {
    throw new Error(`wrangler ${args.slice(0, 3).join(" ")} failed (${result.status}): ${(result.stderr || result.stdout || "").slice(-1500)}`);
  }
  return result.stdout;
}

function migrate() {
  const secrets = loadSecrets();
  const fedA = writeFederationConfig("federation-a", { port: FED_A_PORT, origin: ORIGIN_A, peers: [ORIGIN_B, STUB_C_ORIGIN], secrets: secrets.fedA });
  const fedB = writeFederationConfig("federation-b", { port: FED_B_PORT, origin: ORIGIN_B, peers: [ORIGIN_A, STUB_C_ORIGIN], secrets: secrets.fedB });
  const hub = writeHubConfig();
  const jobs = [
    ["Federation A", "federation-db", fedA.config, PERSIST.fedA],
    ["Federation B", "federation-db", fedB.config, PERSIST.fedB],
    ["Hub B", "HUB_DATABASE", hub.config, PERSIST.hub],
  ];
  for (const [label, binding, config, persist] of jobs) {
    assertInsideStateB(persist);
    mkdirSync(persist, { recursive: true });
    const federationBinding = binding === "federation-db" ? "FEDERATION_DB" : binding;
    const out = runWrangler(["d1", "migrations", "apply", federationBinding, "--local", "--config", config, "--persist-to", persist]);
    console.log(`[migrate] ${label}: ${/No migrations to apply/i.test(out) ? "already up to date" : "applied"}`);
  }
}

function logFile(name) {
  const file = path.join(RUN, `${name}.log`);
  return openSync(file, "a");
}

function start(name, args, cwd, env) {
  const out = logFile(name);
  const child = spawn(process.execPath, args, {
    cwd, env, detached: true, windowsHide: true, stdio: ["ignore", out, out],
  });
  child.unref();
  closeSync(out);
  return child.pid;
}

function pidFile() { return path.join(RUN, "pids.json"); }
function readPids() { try { return JSON.parse(readFileSync(pidFile(), "utf8")); } catch { return {}; } }

async function waitFor(url, label, timeoutMs = 240_000) {
  const started = Date.now();
  while (Date.now() - started < timeoutMs) {
    try {
      const response = await fetch(url, { signal: AbortSignal.timeout(30_000) });
      if (response.ok) return;
    } catch { /* まだ起動中 */ }
    await new Promise((resolve) => setTimeout(resolve, 1000));
  }
  throw new Error(`${label} did not become healthy at ${url}`);
}

async function up() {
  for (const port of [HUB_B_PORT, FED_B_PORT, FED_A_PORT]) {
    if (!(await portFree(port))) throw new Error(`port ${port} is in use; stop the other process or run "down" first`);
  }
  migrate();
  const secrets = loadSecrets();
  const fedA = path.join(RUN, "federation-a", "wrangler.jsonc");
  const fedB = path.join(RUN, "federation-b", "wrangler.jsonc");
  const pids = {};
  const wranglerDev = (config, port, inspector, persist) => [
    wranglerBin, "dev", "--config", config, "--local", "--ip", "127.0.0.1", "--port", String(port),
    "--inspector-port", String(inspector), "--persist-to", persist,
  ];
  pids.federationA = start("federation-a", wranglerDev(fedA, FED_A_PORT, 9341, PERSIST.fedA), repoRoot, wranglerEnv());
  pids.federationB = start("federation-b", wranglerDev(fedB, FED_B_PORT, 9342, PERSIST.fedB), repoRoot, wranglerEnv());

  const hubConfig = path.join(RUN, "hub", "wrangler.jsonc");
  const hubEnv = {
    ...process.env,
    CLOUDFLARE_BINDINGS_LOCAL: "true",
    HUB_WRANGLER_CONFIG: hubConfig,
    HUB_WRANGLER_PERSIST_DIR: PERSIST.hub,
    NEXT_DIST_DIR: ".next-hub-b",
    HUB_DEV_WARM: "0",
    HUB_PUBLIC_ORIGIN: ORIGIN_B,
    HUB_JKAMMA_SERVICES: "0",
    FEDERATION_SERVICE_URL: `http://127.0.0.1:${FED_B_PORT}`,
    HUB_FEDERATION_SECRET: secrets.fedB.serviceSecret,
    HUB_FEDERATION_DEV_ORIGIN: `http://127.0.0.1:${FED_B_PORT}`,
    HUB_DEV_SESSION_PROFILE_ID: USERS.b[0].id,
  };
  for (const key of ["VAULT", "MUSIC", "AI", "IDENTITY", "COMMERCE", "COMPUTE", "MAIL", "SOCIAL_PUBLISHER", "ACCOUNT"]) {
    hubEnv[`HUB_${key}_DEV_ORIGIN`] = DEAD_ORIGIN;
  }
  pids.hubB = start("hub-b", [nextBin, "dev", "--webpack", "-p", String(HUB_B_PORT)], hubRoot, hubEnv);
  writeFileSync(pidFile(), JSON.stringify(pids, null, 2));

  await waitFor(`http://127.0.0.1:${FED_A_PORT}/health`, "Federation A");
  await waitFor(`http://127.0.0.1:${FED_B_PORT}/health`, "Federation B");
  await seed();
  await waitFor(`${ORIGIN_B}/.well-known/nodeinfo`, "Hub B (rewrite to Federation B)");
  console.log(`[up] Hub B ${ORIGIN_B}, Federation B :${FED_B_PORT}, Federation A ${ORIGIN_A}`);
}

async function putFederationProfile(port, secret, user) {
  // The first request after a cold workerd boot can drop the connection; retry briefly.
  let response;
  for (let attempt = 0; ; attempt += 1) {
    try { response = await fetch(`http://127.0.0.1:${port}/v1/profiles/federation`, putInit(secret, user)); break; }
    catch (error) { if (attempt >= 10) throw error; await new Promise((r) => setTimeout(r, 2000)); }
  }
  if (!response.ok) throw new Error(`federation profile upsert failed for ${user.handle}: ${response.status}`);
}

function putInit(secret, user) {
  return {
    method: "PUT",
    headers: { authorization: `Bearer ${secret}`, "content-type": "application/json" },
    body: JSON.stringify({
      profileId: user.id, handle: user.handle, displayName: user.displayName,
      summary: "test-only profile", enabled: true, discoverable: true,
    }),
  };
}

function seedHubProfiles() {
  const now = new Date().toISOString();
  const quote = (value) => `'${String(value).replaceAll("'", "''")}'`;
  const sql = USERS.b.map((user) =>
    `INSERT OR IGNORE INTO profiles (id, handle, display_name, bio, joined_at, created_at, updated_at) VALUES (${[user.id, user.handle, user.displayName, "test-only profile", now, now, now].map(quote).join(", ")});`,
  ).join("\n");
  const file = path.join(RUN, "seed-hub.sql");
  assertInsideStateB(file);
  writeFileSync(file, sql);
  runWrangler(["d1", "execute", "HUB_DATABASE", "--local", "--config", path.join(RUN, "hub", "wrangler.jsonc"), "--persist-to", PERSIST.hub, "--file", file]);
}

async function seed() {
  const secrets = loadSecrets();
  seedHubProfiles();
  for (const user of USERS.a) await putFederationProfile(FED_A_PORT, secrets.fedA.serviceSecret, user);
  for (const user of USERS.b) await putFederationProfile(FED_B_PORT, secrets.fedB.serviceSecret, user);
  console.log(`[seed] Hub B profiles: ${USERS.b.map((u) => u.handle).join(", ")}; Federation A: ${USERS.a[0].handle}`);
}

function killTree(pid) {
  if (!pid) return;
  if (process.platform === "win32") spawnSync("taskkill", ["/PID", String(pid), "/T", "/F"], { stdio: "ignore" });
  else try { process.kill(-pid, "SIGTERM"); } catch { try { process.kill(pid, "SIGTERM"); } catch { /* 既に終了 */ } }
}

async function down() {
  const pids = readPids();
  for (const [name, pid] of Object.entries(pids)) {
    killTree(pid);
    console.log(`[down] stopped ${name} (pid ${pid})`);
  }
  if (existsSync(pidFile())) rmSync(pidFile());
  // 子プロセスの取りこぼし対策: ポートが空くまで待つ。
  for (const port of [HUB_B_PORT, FED_B_PORT, FED_A_PORT]) {
    for (let i = 0; i < 30 && !(await portFree(port)); i += 1) await new Promise((r) => setTimeout(r, 1000));
    if (!(await portFree(port))) console.warn(`[down] port ${port} is still in use`);
  }
}

async function status() {
  const pids = readPids();
  for (const [label, port] of [["Hub B", HUB_B_PORT], ["Federation B", FED_B_PORT], ["Federation A", FED_A_PORT]]) {
    console.log(`${label.padEnd(13)} :${port} ${(await portFree(port)) ? "stopped" : "listening"}`);
  }
  console.log("pids", JSON.stringify(pids));
}

async function reset() {
  await down();
  assertInsideStateB(STATE_B);
  rmSync(STATE_B, { recursive: true, force: true });
  console.log("[reset] removed .wrangler/state-hub-b");
}

const command = process.argv[2];
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const commands = { up, down, status, migrate, seed, reset };
  if (!commands[command]) {
    console.error(`usage: node scripts/dev-hub-b.mjs <${Object.keys(commands).join("|")}>`);
    process.exit(2);
  }
  Promise.resolve(commands[command]()).catch((error) => {
    console.error(error.stack ?? error.message);
    process.exit(1);
  });
}
