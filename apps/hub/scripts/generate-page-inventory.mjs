import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const appRoot = path.resolve(process.cwd(), "app");
const outputPath = path.resolve(process.cwd(), "docs/page-ui-inventory.md");
const registryPath = path.resolve(process.cwd(), "lib/generated-page-ui-registry.ts");

function preserveLineEndings(targetPath, content) {
  const existing = readFileSync(targetPath, "utf8");
  const eol = existing.includes("\r\n") ? "\r\n" : "\n";
  return content.replaceAll("\r\n", "\n").replaceAll("\n", eol);
}

function collectPages(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const absolute = path.join(directory, entry.name);
    if (entry.isDirectory()) return collectPages(absolute);
    return entry.name === "page.tsx" ? [absolute] : [];
  });
}

function toRoute(file) {
  const relative = path.relative(appRoot, path.dirname(file)).replaceAll("\\", "/");
  const segments = relative
    .split("/")
    .filter(Boolean)
    .filter((segment) => !(segment.startsWith("(") && segment.endsWith(")")));
  return segments.length ? `/${segments.join("/")}` : "/";
}

function classify(route) {
  if (/^\/(?:terms|privacy|copyright|about)(?:\/|$)/.test(route)) return "long-form";
  if (/^\/(?:auth|onboarding|appeal)(?:\/|$)/.test(route)) return "form";
  if (/^\/admin(?:\/|$)/.test(route)) return "admin";
  if (/\/(?:new|sell|submit|studio|settings|manage|deploy-[^/]+)$/.test(route)) return "form";
  if (/^\/(?:wallet\/pay|shopping\/orders|market\/orders|shopping\/wallet)(?:\/|$)/.test(route)) return "payment";
  if (/\[[^\]]+\]/.test(route)) return "detail";
  if (/^\/(?:search|market\/search|shopping\/search)(?:\/|$)/.test(route)) return "search";
  if (/^\/(?:ai|compute|messages)(?:\/|$)/.test(route)) return "workspace";
  if (/^\/(?:settings|account|creator|advertising\/dashboard)(?:\/|$)/.test(route)) return "dashboard";
  return "listing";
}

function titleFromSource(file, route) {
  const source = readFileSync(file, "utf8");
  const metadataTitle = source.match(/title:\s*["'`]([^"'`]+)["'`]/)?.[1];
  const heading = source.match(/<h1[^>]*>([^<{]+)<\/h1>/)?.[1]?.trim();
  return metadataTitle ?? heading ?? route;
}

const pages = collectPages(appRoot)
  .map((file) => {
    const route = toRoute(file);
    const source = readFileSync(file, "utf8");
    const redirectTarget = source.match(/\bredirect\(\s*["'`]([^"'`]+)["'`]\s*\)/)?.[1]
      ?? source.match(/\btoV2(?:Permanent)?\(\s*["'`]([^"'`]+)["'`]/)?.[1]
      ?? null;
    return {
      route,
      title: titleFromSource(file, route).replaceAll("|", "\\|"),
      kind: classify(route),
      behavior: redirectTarget ? "redirect" : "rendered",
      redirectTarget,
      source: path.relative(process.cwd(), file).replaceAll("\\", "/"),
    };
  })
  .sort((a, b) => a.route.localeCompare(b.route, "en"));

const counts = new Map();
for (const page of pages) counts.set(page.kind, (counts.get(page.kind) ?? 0) + 1);
const renderedCount = pages.filter((page) => page.behavior === "rendered").length;
const redirectCount = pages.length - renderedCount;

const generated = `# Hub page UI inventory

> Generated by \`npm run generate:page-inventory\`. Do not edit the table manually.
> UI scope is every route backed by \`app/**/page.tsx\`; API and metadata routes are excluded.

## Summary

- Total UI pages: ${pages.length}
- Rendered pages: ${renderedCount}
- Redirect aliases: ${redirectCount}
${[...counts.entries()]
  .sort(([a], [b]) => a.localeCompare(b, "en"))
  .map(([kind, count]) => `- ${kind}: ${count}`)
  .join("\n")}

## Audit states

- \`pending\`: classification is complete; page-specific visual review remains.
- \`shared\`: covered by the shared shell and semantic UI finish layer.
- \`reviewed\`: page-specific structure and responsive states were inspected.
- \`verified\`: reviewed plus tests/build/runtime evidence.
- \`redirect\`: route has no local UI and immediately transfers to the listed destination.

## Pages

| Route | Page label | Type | Behavior | Destination | UI audit | Source |
|---|---|---|---|---|---|---|
${pages
  .map((page) => `| \`${page.route}\` | ${page.title} | ${page.kind} | ${page.behavior} | ${page.redirectTarget ? `\`${page.redirectTarget}\`` : "—"} | ${page.behavior === "redirect" ? "redirect" : "shared"} | \`${page.source}\` |`)
  .join("\n")}
`;

writeFileSync(outputPath, preserveLineEndings(outputPath, generated), "utf8");

const registry = `/* Generated by scripts/generate-page-inventory.mjs. */
export type HubPageKind =
  | "admin"
  | "dashboard"
  | "detail"
  | "form"
  | "listing"
  | "long-form"
  | "payment"
  | "search"
  | "workspace";

export const HUB_PAGE_UI_REGISTRY = ${JSON.stringify(
  pages.map(({ route, kind, behavior, redirectTarget }) => ({
    route,
    kind,
    behavior,
    redirectTarget,
  })),
  null,
  2,
)} as const satisfies readonly {
  route: string;
  kind: HubPageKind;
  behavior: "rendered" | "redirect";
  redirectTarget: string | null;
}[];
`;

writeFileSync(registryPath, preserveLineEndings(registryPath, registry), "utf8");
console.log(`Generated UI inventory and registry for ${pages.length} pages.`);
