export function normalizeBoardKey(key: string) {
  return LEGACY[key] ?? key;
}

export function buildBoardCatalog(): Board[] {
  return BBS_CATEGORIES.flatMap((category) => category.boards.map(([title, description], index) => {
    const key = `${category.key}-board${String(index + 1).padStart(2, "0")}`;
    return { id: `board-${key}`, key, title, slug: `/bbs/${key}`, description, threadCount: 0 };
  }));
}

export function getBoardGroups(boards: Board[]) {
  return BBS_DIRECTORY_GROUPS.map((group) => ({
    key: group.key,
    name: group.name,
    description: group.description,
    boards: boards
      .filter((board) => group.categories.some((categoryKey) => board.key.startsWith(`${categoryKey}-`)))
      .sort((left, right) => right.threadCount - left.threadCount)
  })).filter((group) => group.boards.length);
}

export function getBoardCategory(boardKey: string) {
  const normalizedKey = normalizeBoardKey(boardKey);
  return BBS_CATEGORIES.find((category) => normalizedKey.startsWith(`${category.key}-`));
}

export function normalizeThreads(threads: ThreadSummary[]) {
  return threads.map((thread) => {
    const { communityId: _legacyCommunityId, ...independentThread } = thread as ThreadSummary & { communityId?: string };
    return {
      ...independentThread,
      boardKey: normalizeBoardKey(thread.boardKey),
      language: thread.language ?? "ja",
      region: thread.region ?? "global",
      threadType: getThreadType(thread)
    };
  });
}

export function syncBoardThreadCounts(boards: Board[], threads: ThreadSummary[]) {
  const counts = new Map<string, number>();
  for (const thread of threads) {
    const key = normalizeBoardKey(thread.boardKey);
    counts.set(key, (counts.get(key) ?? 0) + 1);
  }
  for (const board of boards) board.threadCount = counts.get(board.key) ?? 0;
}
